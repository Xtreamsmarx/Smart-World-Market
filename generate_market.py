def _e(text):
    return str(text or '').replace('&','&amp;').replace('<','&lt;').replace('>','&gt;').replace('"','&quot;').replace("'",'&#39;')

def _stars(r):
    r = float(r or 0)
    return '★' * int(r) + ('½' if r % 1 >= 0.5 else '') + '☆' * (5 - int(r) - (1 if r%1>=0.5 else 0))

def _gradient_first(grad):
    """Extract first color from gradient string for simple use."""
    import re
    m = re.search(r'#[0-9a-fA-F]{3,6}', grad)
    return m.group() if m else '#7c3aed'


