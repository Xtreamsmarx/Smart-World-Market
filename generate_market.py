# ── Public API ─────────────────────────────────────────────────────────────────
def generate_product_page_to_disk(product):
    mid    = product['market_id']
    folder = os.path.join(MARKET_DIR, mid)
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, 'index.html'), 'w', encoding='utf-8') as f:
        f.write(make_html(product))
    with open(os.path.join(folder, 'style.css'), 'w', encoding='utf-8') as f:
        f.write(make_style(product))
    with open(os.path.join(folder, 'script.js'), 'w', encoding='utf-8') as f:
        f.write(make_script(product))


def generate_all(skip_existing=False):
    """Generate market pages. skip_existing=True for fast startup."""
    os.makedirs(MARKET_DIR, exist_ok=True)
    products = get_all_products()
    new_count = 0
    for p in products:
        mid    = p['market_id']
        folder = os.path.join(MARKET_DIR, mid)
        if skip_existing and os.path.isfile(os.path.join(folder, 'index.html')):
            continue
        generate_product_page_to_disk(p)
        new_count += 1
    if new_count:
        print(f'[Market] Generated {new_count} page(s).')
    else:
        print('[Market] All market pages are up to date.')


